  await page.getByRole('button',{ name:'Tasks',exact:true }).click();
  await expect(page.getByText('AI planning task',{ exact:true })).toBeVisible();
  await page.screenshot({ path:'mobile/.expo/preview-tasks.png' });
  await page.getByRole('button',{ name:'Undo last change',exact:true }).click();
  await expect(page.getByText('AI planning task',{ exact:true })).toHaveCount(0);
  await page.getByRole('button',{ name:'Assistant',exact:true }).click(); fail = true;
  await page.getByLabel('Message your assistant',{ exact:true }).fill('Keep this request');
  await page.getByRole('button',{ name:'Send',exact:true }).click();
  await expect(page.getByText('Please try again.')).toBeVisible();
